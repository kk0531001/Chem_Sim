// Generates src/content/pageQuestions.ts — which question ids belong to which
// PAGE of a split module (plan3 Phase 6).
//
// Nine high-school modules are shown on two pages: the course page runs the
// first COURSE_SIZE questions of the bank, the contest page the rest. The
// progress bars on the menu cards, the sidebar meters and the /today block all
// need "how much of THIS page is solved", and they render on the entry path,
// which may not import the question banks (CLAUDE.md D.10). So the ids — not
// the questions — are baked into a small data file here.
//
// `--check` re-generates and compares instead of writing: wired into
// `npm run audit` so a reordered bank cannot silently leave the table stale,
// the same guard MODULE_QUIZ_SIZE gets from auditCorpus().
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { QUIZ_BANKS, ROOT } from './corpus.mjs';

/** The modules split into a course page and a `<id>-contest` page. */
const SPLIT = ['stoich', 'quantum', 'periodicity', 'bonding', 'thermo1', 'equilibrium', 'aek', 'labdata', 'labtech'];
/** Positions 1..20 are the course page — mirrors COURSE_QUIZ_SIZE in src/tabs/ui/quiz.ts. */
const COURSE_SIZE = 20;

const OUT = join(ROOT, 'src/content/pageQuestions.ts');

const header = `// GENERATED by scripts/gen-page-questions.mjs — do not edit by hand.
//
// Which question ids each PAGE of a split module owns (plan3 Phase 6): the
// course page holds the first ${COURSE_SIZE} of the module's bank, the contest page the rest.
// Ids, not questions — so \`moduleProgress()\` can count a page's solved
// fraction without the homepage or the menu importing the corpus (D.10).
//
// Re-generate with \`node scripts/gen-page-questions.mjs\`; \`npm run audit\`
// fails if this file has drifted from the banks.
export const PAGE_QUESTION_IDS: Record<string, readonly string[]> = {
`;

let body = '';
for (const mod of SPLIT) {
  const bank = QUIZ_BANKS[mod];
  if (!bank) throw new Error(`gen-page-questions: no quiz bank for "${mod}"`);
  const ids = bank.map(q => q.id);
  if (ids.some(id => !id)) throw new Error(`gen-page-questions: ${mod} has a question with no id`);
  // Six per line: a page's list stays readable in a diff when one bank is
  // reordered, instead of one 900-character line changing wholesale.
  const wrap = list => list.reduce((rows, id, i) => {
    if (i % 6 === 0) rows.push([]);
    rows[rows.length - 1].push(`'${id}'`);
    return rows;
  }, []).map(row => '    ' + row.join(', ') + ',').join('\n');
  body += `  '${mod}': [\n${wrap(ids.slice(0, COURSE_SIZE))}\n  ],\n`;
  body += `  '${mod}-contest': [\n${wrap(ids.slice(COURSE_SIZE))}\n  ],\n`;
}
const text = header + body + '};\n';

if (process.argv.includes('--check')) {
  const have = readFileSync(OUT, 'utf8');
  if (have !== text) {
    console.error('  pageQuestions: STALE — a split module\'s bank changed.\n  Run: node scripts/gen-page-questions.mjs');
    process.exit(1);
  }
  console.log(`  pageQuestions: up to date (${SPLIT.length} modules, ${SPLIT.length * 2} pages)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote src/content/pageQuestions.ts — ${SPLIT.length * 2} pages`);
}
